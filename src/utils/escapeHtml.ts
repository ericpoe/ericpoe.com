/**
 * Escapes the five HTML-significant characters. Shared by the summary and
 * caption sanitizers so the entity set can't drift between them.
 */
export function escapeHtml(value: string): string {
  return value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}
